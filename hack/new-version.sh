#!/usr/bin/env bash
# Writes versions/<version>.yaml for one upstream rke2 release.
#
# The image list and the RPM digests cannot come from a template: `cargoship dev render` reads
# nothing but its own inputs, by design, so a render is reproducible. This is the step that
# turns an upstream tag into those inputs.
#
#   hack/new-version.sh v1.37.2+rke2r1
#
# Exits non-zero without writing anything if any artifact the definition would declare is no
# longer fetchable, which is what upstream retiring a revision looks like.
set -euo pipefail

tag=${1:-}
if [[ -z $tag ]]; then
  echo "usage: ${0##*/} <upstream-tag>   e.g. ${0##*/} v1.37.2+rke2r1" >&2
  exit 2
fi
if [[ ! $tag =~ ^v([0-9]+)\.([0-9]+)\.[0-9]+\+rke2r[0-9]+$ ]]; then
  echo "not an rke2 release tag: $tag" >&2
  exit 2
fi

# The four forms of one version. Upstream spells it three ways and the repository path a
# fourth, so every one of them is derived here rather than at each use.
minor="${BASH_REMATCH[1]}.${BASH_REMATCH[2]}"   # 1.37        -- the RPM repository path
version=${tag#v}; version=${version/+/-}        # 1.37.2-rke2r1  -- metadata.version, image tags
rpm_version=${version/-/\~}                     # 1.37.2~rke2r1  -- RPM file names

root=$(cd "$(dirname "$(readlink -f "$0")")" && git rev-parse --show-toplevel)
out="$root/versions/$version.yaml"
rpm_base="https://rpm.rancher.io/rke2/latest/$minor/centos/9/x86_64"
selinux_base="https://rpm.rancher.io/rke2/latest/common/centos/9/noarch"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Fetch and hash in one pass. A retired revision keeps its git tag long after its packages
# have gone, so a definition that renders from one would install nowhere -- curl --fail here
# is the check that catches it, and the only reason this script needs a network.
sha_of() {
  local url=$1 sum
  sum=$(curl -fsSL --retry 3 "$url" | sha256sum | cut -d' ' -f1) ||
    { echo "not fetchable, upstream has probably retired this revision: $url" >&2; return 1; }
  [[ $sum == e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855 ]] &&
    { echo "empty body: $url" >&2; return 1; }
  echo "$sum"
}

# Newest rke2-selinux in the common repository. It moves on its own schedule rather than with
# the kubernetes minor, so it is resolved rather than pinned alongside the version.
primary=$(curl -fsSL "$selinux_base/repodata/repomd.xml" |
  grep -oE 'href="repodata/[^"]*primary\.xml\.gz"' | head -1 | sed 's/^href="//;s/"$//')
selinux_rpm=$(curl -fsSL "$selinux_base/$primary" | gunzip |
  grep -oE '<location href="[^"]*rke2-selinux[^"]*"' | sed 's/.*href="//;s/"$//' |
  sort -V | tail -1)
[[ -n $selinux_rpm ]] || { echo "found no rke2-selinux in $selinux_base" >&2; exit 1; }
selinux_version=${selinux_rpm#rke2-selinux-}; selinux_version=${selinux_version%.el9.noarch.rpm}

# Upstream's own lists, concatenated in this order. Verified byte-identical to the image list
# this repository carried by hand, so the two files pass straight through uncurated.
gh release download "$tag" --repo rancher/rke2 --dir "$work" --skip-existing \
  --pattern 'rke2-images-core.linux-amd64.txt' \
  --pattern 'rke2-images-cilium.linux-amd64.txt'
cat "$work/rke2-images-core.linux-amd64.txt" "$work/rke2-images-cilium.linux-amd64.txt" \
  > "$work/images.txt"

# etcdctl is not shipped by rke2 and is the tool you want on a control-plane node when etcd
# is the thing that is wrong. The version is taken from the hardened-etcd image this release
# bundles rather than pinned here, so the client always matches the server it talks to.
etcd_version=$(grep -oE 'hardened-etcd:v[0-9]+\.[0-9]+\.[0-9]+' "$work/images.txt" |
  head -1 | sed 's/.*:v//')
[[ -n $etcd_version ]] || { echo "no hardened-etcd image in the list for $tag" >&2; exit 1; }
etcd_url="https://github.com/etcd-io/etcd/releases/download/v$etcd_version/etcd-v$etcd_version-linux-amd64.tar.gz"

sha_etcd=$(sha_of "$etcd_url")
sha_common=$(sha_of "$rpm_base/rke2-common-$rpm_version-0.el9.x86_64.rpm")
sha_server=$(sha_of "$rpm_base/rke2-server-$rpm_version-0.el9.x86_64.rpm")
sha_agent=$(sha_of "$rpm_base/rke2-agent-$rpm_version-0.el9.x86_64.rpm")
sha_selinux=$(sha_of "$selinux_base/$selinux_rpm")

# Nothing is written until every input is in hand, so an interrupted run leaves no values file
# that renders a package missing half its artifacts.
images=$(grep -c . "$work/images.txt")
if ((images == 0)); then
  echo "upstream published no images for $tag" >&2
  exit 1
fi

mkdir -p "$root/versions"
{
  echo "---"
  echo "# Generated by hack/new-version.sh $tag -- do not hand-edit."
  echo "version: $version"
  echo "rpmVersion: $rpm_version"
  echo "minor: \"$minor\""
  echo "selinux:"
  echo "  version: $selinux_version"
  echo "  shasum: $sha_selinux"
  echo "etcd:"
  echo "  version: $etcd_version"
  echo "  shasum: $sha_etcd"
  echo "rpms:"
  echo "  common: $sha_common"
  echo "  server: $sha_server"
  echo "  agent: $sha_agent"
  echo "images:"
  sed 's/^/  - /' "$work/images.txt"
} > "$out"

echo "wrote ${out#"$root"/} ($images images, rke2-selinux $selinux_version, etcdctl $etcd_version)"
